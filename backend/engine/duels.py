import sqlite3
import random
import re
from typing import List, Tuple, Optional

class DuelEngine:
    def __init__(self, db_path: str = 'data/game_dictionary.db'):
        self.db_path = db_path

    def _get_db_connection(self):
        return sqlite3.connect(self.db_path)

    def check_correct_spelling(self, word_to_spell: str, user_spelling: str) -> bool:
        """
        Checks if the user spelled the word correctly.
        """
        return word_to_spell.lower() == user_spelling.lower()

    def check_mental_arithmetic(self, sequence: str, user_answer: int) -> bool:
        """
        Validates the result of a mental arithmetic sequence.
        """
        try:
            # We use eval safely here because the sequence is generated by our engine
            result = eval(sequence)
            return result == user_answer
        except Exception:
            return False

    def check_one_within_the_other(self, large_word: str, small_word: str) -> bool:
        """
        Validates 'One within the other'.
        """
        if len(large_word) != 10:
            return False
        
        if small_word.lower() in large_word.lower():
            conn = self._get_db_connection()
            cursor = conn.cursor()
            cursor.execute("SELECT word FROM words WHERE word = ?", (small_word,))
            exists = cursor.fetchone()
            conn.close()
            return exists is not None
        
        return False

    def check_classic_duel(self, word1: str, word2: str, letters_provided: List[str]) -> bool:
        """
        Validates the 'Classic' duel.
        1. Both words must be in the dictionary.
        2. The total letters used must exactly match the letters_provided.
        """
        conn = self._get_db_connection()
        cursor = conn.cursor()
        
        cursor.execute("SELECT word FROM words WHERE word = ?", (word1,))
        w1_exists = cursor.fetchone()
        cursor.execute("SELECT word FROM words WHERE word = ?", (word2,))
        w2_exists = cursor.fetchone()
        conn.close()

        if not w1_exists or not w2_exists:
            return False

        combined_words = (word1 + word2).lower()
        combined_counts = {}
        for char in combined_words:
            if char.isalpha():
                combined_counts[char] = combined_counts.get(char, 0) + 1

        available_counts = {}
        for char in letters_provided:
            char_lower = char.lower()
            available_counts[char_lower] = available_counts.get(char_lower, 0) + 1

        for char, count in combined_counts.items():
            if available_counts.get(char, 0) != count:
                return False
        
        if len(combined_counts) > len(available_counts):
            return False

        return True

